//! Generated artifacts: TS types, JSON Schemas, the node catalog docs and fixture — plus drift checks.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, bail};
use serde_json::Value;

use crate::{root, run};

/// Regenerates `types_dir` (ts-rs) and `contracts_dir` (JSON Schema).
pub fn types(types_dir: &Path, contracts_dir: &Path) -> anyhow::Result<()> {
    if types_dir.exists() {
        fs::remove_dir_all(types_dir)?;
    }
    fs::create_dir_all(types_dir)?;
    run(
        "ts-rs export",
        Command::new("cargo")
            .args(["test", "-p", "il-core", "--quiet", "export_bindings"])
            .env("TS_RS_EXPORT_DIR", types_dir),
    )?;
    let mut paths = Vec::new();
    list_files(types_dir, types_dir, &mut paths)?;
    let mut files: Vec<String> = paths
        .iter()
        .filter(|p| p.extension().is_some_and(|e| e == "ts") && p.file_name().is_some_and(|n| n != "index.ts"))
        .map(|p| p.to_string_lossy().replace('\\', "/"))
        .collect();
    files.sort();
    let mut index = String::from("// Generated by `cargo xtask gen-types`. Do not edit.\n");
    for f in &files {
        index.push_str(&format!("export type * from './{}';\n", f.trim_end_matches(".ts")));
    }
    fs::write(types_dir.join("index.ts"), index)?;

    fs::create_dir_all(contracts_dir)?;
    let schemas = il_core::contracts::json_schemas();
    for (name, schema) in &schemas {
        fs::write(contracts_dir.join(format!("{name}.json")), serde_json::to_string_pretty(schema)? + "\n")?;
    }
    eprintln!("  {} TS files, {} JSON Schemas", files.len(), schemas.len());
    Ok(())
}

/// Writes `docs/NODES.md` and the fixture catalog from the server's registered manifests.
pub fn catalog(md_path: &Path, fixture_path: &Path) -> anyhow::Result<()> {
    let catalog = load_catalog()?;
    fs::write(md_path, render_markdown(&catalog))?;
    if let Some(parent) = fixture_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(fixture_path, serde_json::to_string_pretty(&catalog)? + "\n")?;
    eprintln!("  wrote {} and {}", md_path.display(), fixture_path.display());
    Ok(())
}

fn load_catalog() -> anyhow::Result<Value> {
    let out = Command::new("cargo")
        .args(["run", "--quiet", "-p", "il-server", "--", "catalog"])
        .output()
        .context("running il-server catalog")?;
    if !out.status.success() {
        bail!("il-server catalog failed: {}", String::from_utf8_lossy(&out.stderr));
    }
    Ok(serde_json::from_slice(&out.stdout)?)
}

fn render_markdown(catalog: &Value) -> String {
    let mut by_cat: BTreeMap<String, Vec<&Value>> = BTreeMap::new();
    for n in catalog["nodes"].as_array().into_iter().flatten() {
        by_cat.entry(n["category"].as_str().unwrap_or("other").to_string()).or_default().push(n);
    }
    let total: usize = by_cat.values().map(Vec::len).sum();
    let mut md = format!(
        "# Node catalog\n\nGenerated by `cargo xtask catalog` from registered manifests. Do not edit by hand.\n\n{total} node types.\n"
    );
    for (cat, nodes) in by_cat {
        md.push_str(&format!(
            "\n## {}\n\n| Type | Title | Status | Ports (in → out) | Description |\n|---|---|---|---|---|\n",
            title_case(&cat)
        ));
        for n in nodes {
            let ports = |key: &str| {
                n[key]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .filter_map(|p| p["name"].as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let mut outs = ports("outputs");
            if let Some(d) = n["dynamicOutputs"].as_str() {
                outs = if outs.is_empty() { format!("from `{d}`") } else { format!("{outs} + from `{d}`") };
            }
            md.push_str(&format!(
                "| `{}` | {} | {} | {} → {} | {} |\n",
                n["typeId"].as_str().unwrap_or_default(),
                n["title"].as_str().unwrap_or_default(),
                n["status"].as_str().unwrap_or_default(),
                if ports("inputs").is_empty() { "—".into() } else { ports("inputs") },
                if outs.is_empty() { "—".into() } else { outs },
                n["description"].as_str().unwrap_or_default().replace('|', "\\|"),
            ));
        }
    }
    md
}

fn title_case(s: &str) -> String {
    match s {
        "ai" => "AI".into(),
        _ => s[..1].to_uppercase() + &s[1..],
    }
}

/// Fails if generated types, schemas or the catalog differ from what is committed.
pub fn drift() -> anyhow::Result<()> {
    let root = root();
    let tmp = root.join("target/xtask-drift");
    if tmp.exists() {
        fs::remove_dir_all(&tmp)?;
    }
    types(&tmp.join("types"), &tmp.join("contracts"))?;
    catalog(&tmp.join("NODES.md"), &tmp.join("nodes.json"))?;
    let mut diffs = Vec::new();
    compare_dirs(&tmp.join("types"), &root.join("web/src/lib/api/types"), &mut diffs)?;
    compare_dirs(&tmp.join("contracts"), &root.join("contracts"), &mut diffs)?;
    compare_file(&tmp.join("NODES.md"), &root.join("docs/NODES.md"), &mut diffs);
    compare_file(&tmp.join("nodes.json"), &root.join("web/fixtures/api/nodes.json"), &mut diffs);
    if !diffs.is_empty() {
        for d in &diffs {
            eprintln!("  out of date: {d}");
        }
        bail!("generated files are out of date: run `cargo xtask gen-types` and `cargo xtask catalog`, then commit");
    }
    eprintln!("  generated files are up to date");
    Ok(())
}

fn compare_dirs(fresh: &Path, committed: &Path, diffs: &mut Vec<String>) -> anyhow::Result<()> {
    let mut a = Vec::new();
    let mut b = Vec::new();
    list_files(fresh, fresh, &mut a)?;
    if committed.exists() {
        list_files(committed, committed, &mut b)?;
    }
    for rel in a.iter().chain(b.iter().filter(|f| !a.contains(f))) {
        compare_file(&fresh.join(rel), &committed.join(rel), diffs);
    }
    Ok(())
}

fn list_files(base: &Path, dir: &Path, out: &mut Vec<PathBuf>) -> anyhow::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            list_files(base, &path, out)?;
        } else {
            out.push(path.strip_prefix(base)?.to_path_buf());
        }
    }
    Ok(())
}

fn compare_file(fresh: &Path, committed: &Path, diffs: &mut Vec<String>) {
    let norm = |p: &Path| fs::read_to_string(p).ok().map(|s| s.replace("\r\n", "\n"));
    if norm(fresh) != norm(committed) {
        diffs.push(committed.display().to_string());
    }
}
